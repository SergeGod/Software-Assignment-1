#!/usr/bin/env bash
# Publishes the static UI to the storage account's static website. Run by cd.yml.
#   infra/deploy-ui.sh <ledger-url> <settlement-url>
# Needs: az logged in. Prints the UI's https URL on the last line.
set -euo pipefail
source "$(dirname "$0")/config.sh"

ledger_url=$1
settlement_url=$2

# The UI is plain files, so "building" it is copying ui/ and writing config.js
# with the URLs of the services just deployed. The copy in the repository
# (localhost URLs, for compose) is left untouched.
build=$(mktemp -d)
cp -R "$(dirname "$0")/../ui/." "$build/"
cat > "$build/config.js" <<EOF
// Generated by the CD pipeline from commit ${GITHUB_SHA:-local}.
window.TABBY_CONFIG = {
  ledgerUrl: "$ledger_url",
  settlementUrl: "$settlement_url",
};
EOF

# no-cache: the browser asks again on every visit, so a new deployment (and a
# new config.js) is picked up at once. The files are a few kilobytes.
az storage blob upload-batch --account-name "$UI_STORAGE" --auth-mode key \
  --destination '$web' --source "$build" --overwrite \
  --content-cache-control "no-cache" --output none

"$(dirname "$0")/ui-url.sh"
